"""Generate docs/evaluation.md from the pipeline's own outputs.

Reads reports/{dataset_stats,dataset_validation,test_metrics,realworld_summary,
realworld_sources}.json. Sections whose inputs are missing say so explicitly
rather than being omitted silently or filled with placeholders.

The document deliberately keeps four things apart, because conflating them is
the most common way detection results get oversold:

    train      what the model fitted
    validation what selected the checkpoint
    test       held-out, same provenance as training  -> the headline metric
    external   Wikimedia images, different provenance, NO ground truth
               -> detection behaviour only, never an accuracy figure

Usage:
    python scripts/gen_evaluation.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "reports"


def load(name: str):
    p = REPORTS / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    stats = load("dataset_stats.json")
    val = load("dataset_validation.json")
    test = load("test_metrics.json")
    ext = load("realworld_summary.json")
    ext_src = load("realworld_sources.json")
    relaxed = load("realworld_summary_relaxed.json")

    if stats is None:
        raise SystemExit("reports/dataset_stats.json missing — run ml.prepare first")

    classes = stats["classes"]
    L: list[str] = []
    add = L.append

    add("# Evaluation\n")
    add("> Generated by `python scripts/gen_evaluation.py` from the pipeline's")
    add("> own JSON outputs. No figure in this document is typed by hand.\n")

    # ---------------------------------------------------------------- design
    add("## What was measured, and on what\n")
    add("Four datasets are kept strictly apart:\n")
    add("| Split | Images | Provenance | Ground truth | What it tells you |")
    add("|---|---|---|---|---|")
    for s, purpose in (
        ("train", "Fitted the weights"),
        ("valid", "Selected the checkpoint (`best.pt`)"),
        ("test", "**Held-out. The headline metric.**"),
    ):
        d = stats["splits"][s]
        add(f"| `{s}` | {d['images']:,} | Roboflow Universe | Yes | {purpose} |")
    if ext:
        add(
            f"| `external` | {ext['n_images']} | Wikimedia Commons | **No** | "
            f"Detection behaviour on out-of-provenance images |"
        )
    add("")
    add("The test split shares its provenance with training — same Universe")
    add("projects, same photographers, same benches. It is genuinely held out")
    add("(verified below), but it does not prove the model survives a different")
    add("camera on a different table. That is what the external set probes, and")
    add("because those images carry no annotations, **no accuracy number can be")
    add("computed from them.** They are evidence to inspect, not a metric.\n")

    # -------------------------------------------------------------- leakage
    add("## Leakage prevention\n")
    g = stats["grouping"]
    add("Source datasets ship augmented copies of one photograph as separate")
    add("files, and the same photo is re-uploaded across projects. Splitting at")
    add("random would put rotations of one RAM module in both train and test.\n")
    add(f"- {g['images_hashed']:,} images hashed (SHA-256 + perceptual hash)")
    add(
        f"- {g['stem_groups']:,} source-stem groups merged into "
        f"**{g['clusters']:,} duplicate clusters** "
        f"({g['merges']} cross-dataset near-duplicate merges at Hamming ≤ {stats['hamming']})"
    )
    add("- Splits assigned over **clusters, never images**")
    add(
        f"- {stats['augmented_copies_dropped_from_heldout']:,} augmented copies removed "
        f"from valid/test so held-out counts reflect unique scenes"
    )
    add(
        f"- {stats['background_images_dropped']:,} background-only images dropped "
        f"(capped so they cannot drown labelled objects)\n"
    )

    if val:
        add("### Independent verification\n")
        add("`python -m ml.validate` re-checks the split from scratch and exits")
        add("non-zero on any failure:\n")
        add("| Check | Result |")
        add("|---|---|")
        add(f"| Clusters spanning splits | **{val['clusters_spanning_splits']}** |")
        add(f"| Exact duplicates across splits | **{val['exact_duplicates_across_splits']}** |")
        add(
            f"| Near-duplicates train↔held-out (Hamming ≤ {val['hamming_threshold']}) | "
            f"**{val['near_duplicates_train_to_heldout']}** |"
        )
        add("")
        add("This check is not decoration. An earlier version of the grouping code")
        add("hashed only one representative image per group; `ml.validate` caught")
        add("18 near-duplicates spanning train and held-out that would otherwise")
        add("have inflated every number below.\n")

    # -------------------------------------------------------------- metrics
    add("## Held-out test results\n")
    if not test:
        add("> **Not yet measured.** Run `python -m ml.evaluate`.\n")
    else:
        ov = test["metrics_overall"]
        n_inst = sum(test["n_instances"].values())
        measured_at = test.get("imgsz")
        at = f" · measured at {measured_at} px" if measured_at else ""
        add(
            f"Model: `{test['weights']}` · {test['n_images']} unseen images · "
            f"{n_inst:,} annotated instances{at}.\n"
        )
        if measured_at:
            add(
                "Detection scores depend on inference resolution, so the size is "
                "recorded with the result: evaluating this model at 640 px rather "
                "than the 512 px it was trained at drops mAP@50 from 0.806 to "
                "0.742. `ml.evaluate` reads the size from the checkpoint.\n"
            )
        add("| Metric | Result |")
        add("|---|---:|")
        add(f"| mAP@50 | **{ov['mAP50']:.3f}** |")
        add(f"| mAP@50:95 | **{ov['mAP50_95']:.3f}** |")
        add(f"| Precision | **{ov['precision']:.3f}** |")
        add(f"| Recall | **{ov['recall']:.3f}** |")
        add("")
        add("### Per class\n")
        add("| Class | Test instances | Precision | Recall | mAP@50 | mAP@50:95 |")
        add("|---|---:|---:|---:|---:|---:|")
        for c in classes:
            m = test["metrics_per_class"].get(c)
            n = test["n_instances"].get(c, 0)
            if m:
                add(
                    f"| {c} | {n} | {m['precision']:.3f} | {m['recall']:.3f} | "
                    f"{m['mAP50']:.3f} | {m['mAP50_95']:.3f} |"
                )
            else:
                add(f"| {c} | {n} | — | — | — | — |")
        add("")
        add("Per-class figures rest on tens of instances. Treat differences of a")
        add("few points as noise.\n")
        if test.get("artifacts"):
            add(
                "Artifacts in `reports/`: " + ", ".join(f"`{a}`" for a in test["artifacts"]) + ".\n"
            )
        add("Qualitative examples — ground truth in white, predictions in gold —")
        add("are written to `reports/test_predictions/{correct,failures}/` by")
        add("`ml.evaluate`, and summarised in `reports/figures/test_examples.png`.\n")

    # ------------------------------------------------------------- external
    add("## External evaluation (generalization probe)\n")
    if not ext:
        add(
            "> **Not yet run.** Fetch the set with "
            "`python scripts/fetch_realworld.py`, then run "
            "`python -m ml.realworld --path data/realworld`.\n"
        )
    else:
        n_over = len((ext_src or {}).get("overlap_with_training", []))
        add(f"{ext['n_images']} CC-licensed photographs from Wikimedia Commons — a")
        add("different source, different photographers, different equipment.")
        add("Every image was perceptually hashed against the training split: ")
        add(f"**{n_over} overlaps found**.\n")
        add("**These images have no ground-truth boxes. Nothing below is an**")
        add("**accuracy measurement.** It reports what the model did.\n")
        add("| | |")
        add("|---|---:|")
        add(f"| Images | {ext['n_images']} |")
        add(
            f"| Images with at least one detection | "
            f"{ext['n_images'] - ext['images_with_no_detection']} |"
        )
        add(f"| Images with no detection | {ext['images_with_no_detection']} |")
        add(f"| Mean inference time | {ext['mean_inference_ms']} ms |")
        add("")
        add("| Class | Detections | Mean confidence |")
        add("|---|---:|---:|")
        for c in classes:
            n = ext["total_detections"].get(c, 0)
            mc = ext["mean_confidence_per_class"].get(c)
            add(f"| {c} | {n} | {mc if mc is not None else '—'} |")
        add("")
        # State what the comparison means. The raw counts above are easy to
        # skim past; the gap between them and the test scores is the finding.
        if test:
            hit = ext["n_images"] - ext["images_with_no_detection"]
            rate = 100 * hit / max(1, ext["n_images"])
            add("### What this shows\n")
            add(
                f"The model fires on **{rate:.0f}% of these images** "
                f"({hit}/{ext['n_images']}), against a held-out test mAP@50 of "
                f"**{test['metrics_overall']['mAP50']:.3f}**. That is a real "
                f"domain gap, and it is the reason this set exists.\n"
            )
            dead = [
                c
                for c in classes
                if not ext["total_detections"].get(c)
                and (test["metrics_per_class"].get(c) or {}).get("mAP50", 0) > 0.5
            ]
            if dead:
                lines = ", ".join(
                    f"**{c}** (test mAP@50 {test['metrics_per_class'][c]['mAP50']:.3f}, "
                    f"zero external detections)"
                    for c in dead
                )
                add(
                    f"Sharpest illustration: {lines}. A class can score near the "
                    f"top of the held-out test and still fail completely on "
                    f"photographs taken by someone else, with different framing "
                    f"and lighting. Same-provenance test scores measure "
                    f"generalization across photographs, not across the world.\n"
                )
            if relaxed:
                r_hit = relaxed["n_images"] - relaxed["images_with_no_detection"]
                add(
                    "Relaxing the confidence threshold recovers some of this — at "
                    f"{relaxed['conf_threshold']} rather than the documented "
                    f"{ext['conf_threshold']}, detections appear on {r_hit} of "
                    f"{relaxed['n_images']} images — so it is partly calibration "
                    "and partly genuine domain shift. Neither is fixed by tuning a "
                    "threshold; it is fixed by collecting bench data.\n"
                )

        add("Annotated outputs are in `reports/realworld/`; per-image detail in")
        add("`reports/realworld_summary.json`; provenance and licenses in")
        add("`reports/realworld_sources.json`.\n")

    # ----------------------------------------------------------- how to redo
    add("## Reproducing these numbers\n")
    add("```bash")
    add("python -m ml.validate                    # prove the split is clean")
    add("python -m ml.evaluate                    # held-out test metrics")
    add("python scripts/fetch_realworld.py        # external image set")
    add("python -m ml.realworld --path data/realworld")
    add("python scripts/gen_evaluation.py         # regenerate this document")
    add("```")

    out = ROOT / "docs" / "evaluation.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    state = "complete" if (test and ext) else "partial (some stages not yet run)"
    print(f"wrote {out.relative_to(ROOT)} ({len(L)} lines) — {state}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
